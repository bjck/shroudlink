"""Generate mod/sdk/src/event_types.rs from the server's reflection data.

usage: python eventtypes.py <reflection_data.json from kfc-parser extract-types>

Every `keen::ecs` type derived from `keen::ecs::Event` with its `qualifiedHash` (the id the
game writes into its event queue; a hash of the qualified type name) and payload size.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "mod" / "sdk" / "src" / "event_types.rs"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    by_index = {t["index"]: t for t in data["types"]}

    def is_event(t, depth=0):
        if t["qualifiedName"] == "keen::ecs::Event":
            return True
        inner = t.get("innerType")
        return depth < 8 and inner in by_index and is_event(by_index[inner], depth + 1)

    rows = sorted(
        {
            (t["qualifiedHash"], t["qualifiedName"].split("::")[-1], t["size"])
            for t in data["types"]
            if t["qualifiedName"].startswith("keen::ecs::") and t["qualifiedName"] != "keen::ecs::Event" and is_event(t)
        }
    )
    lines = [
        "//! Event types of the server ECS, generated by research/scripts/eventtypes.py from the",
        "//! game's reflection data: the id the game writes into its event queue (a hash of the",
        "//! qualified type name), the type name and the payload size in bytes.",
        "",
        "pub const EVENT_TYPES: &[(u32, &str, u16)] = &[",
        *[f'    ({h:#010x}, "{n}", {s}),' for h, n, s in rows],
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(rows)} event types -> {OUT}")


if __name__ == "__main__":
    main()
