"""Generate mod/sdk/src/component_types.rs from the server's reflection data.

usage: python componenttypes.py <reflection_data.json from kfc-parser extract-types>

Every `keen::ecs` type derived from `keen::ecs::Component` with its `qualifiedHash` (what the
world's component descriptor table holds, see server/src/components.rs) and size.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "mod" / "sdk" / "src" / "component_types.rs"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    by_index = {t["index"]: t for t in data["types"]}

    def is_component(t, depth=0):
        if t["qualifiedName"] == "keen::ecs::Component":
            return True
        inner = t.get("innerType")
        return depth < 8 and inner in by_index and is_component(by_index[inner], depth + 1)

    rows = sorted(
        {
            (t["qualifiedHash"], t["qualifiedName"].split("::")[-1], t["size"])
            for t in data["types"]
            if t["qualifiedName"].startswith("keen::ecs::") and t["qualifiedName"] != "keen::ecs::Component" and is_component(t)
        }
    )
    lines = [
        "//! Component types of the server ECS, generated by research/scripts/componenttypes.py",
        "//! from the game's reflection data: `qualifiedHash` (the id in the world's component",
        "//! descriptor table), the type name and its size in bytes. Field layouts are in the",
        "//! reflection data (research/scripts/reflect.py).",
        "",
        "pub const COMPONENT_TYPES: &[(u32, &str, u16)] = &[",
        *[f'    ({h:#010x}, "{n}", {s}),' for h, n, s in rows],
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(rows)} component types -> {OUT}")


if __name__ == "__main__":
    main()
