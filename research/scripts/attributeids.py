"""Generate mod/sdk/src/attribute_ids.rs (shroudlink_sdk::attr) from the attribute ids
exported from the game's AttributeContainer with EML (one line per group:
`Group <value type> Slot=0xid Slot=0xid ...`).

usage: python attributeids.py <attribute_ids.txt>
"""
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "mod" / "sdk" / "src" / "attribute_ids.rs"


def main():
    slots = {}
    for line in Path(sys.argv[1]).read_text(encoding="utf-8").splitlines():
        for name, value in re.findall(r"(\w+)=0x([0-9a-f]{8})", line):
            slots[name] = int(value, 16)
    rows = sorted(slots.items())
    out = [
        "//! Attribute slot ids of the server (the hash of each slot's name), generated by",
        "//! research/scripts/attributeids.py from the game's AttributeContainer.",
        "",
    ]
    for name, value in rows:
        out.append(f"pub const {name.upper()}: u32 = {value:#010x};")
    out += ["", "/// Every slot by name.", "pub const ALL: &[(u32, &str)] = &["]
    out += [f"    ({value:#010x}, \"{name}\")," for name, value in rows]
    out += ["];", ""]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(rows)} attribute slots -> {OUT}")


if __name__ == "__main__":
    main()
